class FakeResult:
    def __init__(self, data):
        self.data = data


class FakeQuery:
    """
    Same shape as test_provider_agent_workflow.py's fake, plus neq/is_
    (patient_detail's alerts query needs neq) and insert (create_follow_up
    needs it) — the two existing fakes in this test suite each cover only
    part of what these routes call.
    """

    def __init__(self, rows):
        self._rows = rows  # live reference into FakeSupabase.tables[name]
        self._predicates = []
        self._limit = None
        self._descending = False
        self._order_column = None
        self._update_fields = None
        self._insert_row = None

    def select(self, *_args, **_kwargs):
        return self

    def eq(self, column, value):
        self._predicates.append(lambda row, c=column, v=value: row.get(c) == v)
        return self

    def neq(self, column, value):
        self._predicates.append(lambda row, c=column, v=value: row.get(c) != v)
        return self

    def in_(self, column, values):
        self._predicates.append(lambda row, c=column, vs=values: row.get(c) in vs)
        return self

    def is_(self, column, value):
        assert value == "null"
        self._predicates.append(lambda row, c=column: row.get(c) is None)
        return self

    def order(self, column, desc=False, **_kwargs):
        self._order_column = column
        self._descending = desc
        return self

    def limit(self, value):
        self._limit = value
        return self

    def update(self, fields):
        self._update_fields = fields
        return self

    def insert(self, fields):
        # Mirrors follow_up_actions' real schema defaults (id/created_at
        # generated by Postgres) — the fake has to fill these in itself
        # since nothing here talks to a real database.
        row = {
            "id": f"generated-{len(self._rows) + 1}",
            "created_at": NOW,
            **fields,
        }
        self._insert_row = row
        return self

    def execute(self):
        if self._insert_row is not None:
            self._rows.append(self._insert_row)
            return FakeResult([deepcopy(self._insert_row)])
        matched = [row for row in self._rows if all(p(row) for p in self._predicates)]
        if self._update_fields is not None:
            for row in matched:
                row.update(self._update_fields)
        if self._order_column is not None:
            matched.sort(
                key=lambda row: row.get(self._order_column) or "",
                reverse=self._descending,
            )
        if self._limit is not None:
            matched = matched[: self._limit]
        return FakeResult([deepcopy(row) for row in matched])


class FakeSupabase:
    def __init__(self, tables):
        self.tables = deepcopy(tables)

    def table(self, name):
        return FakeQuery(self.tables.setdefault(name, []))


def _user(role="provider", user_id=PROVIDER_USER_ID):
    return CurrentUser(id=user_id, email="provider@example.com", role=role, is_active=True)


def _authorize(fake, role="provider"):
    app.dependency_overrides[get_current_user] = lambda: _user(role=role)
    app.dependency_overrides[get_supabase_client] = lambda: fake


