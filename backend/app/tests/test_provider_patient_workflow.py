# --- GET /provider/patients/{id} -------------------------------------------


def test_patient_detail_includes_clinical_profile_fields_and_assigned_provider():
    fake = FakeSupabase(_base_tables())
    _authorize(fake)

    response = client.get(f"/provider/patients/{PATIENT_ID}")

    assert response.status_code == 200
    profile = response.json()["profile"]
    assert profile["condition"] == "Hypertension"
    assert profile["clinic"] == "Colombo Cardiac"
    assert profile["enrolled_at"] is not None
    assert response.json()["assigned_provider_name"] == PROVIDER_NAME


def test_patient_detail_follow_ups_carry_provider_names():
    fake = FakeSupabase(_base_tables(follow_ups=[_follow_up_row()]))
    _authorize(fake)

    response = client.get(f"/provider/patients/{PATIENT_ID}")

    assert response.status_code == 200
    follow_up = response.json()["follow_ups"][0]
    assert follow_up["provider_full_name"] == PROVIDER_NAME
    assert follow_up["assigned_to_provider_name"] == OTHER_PROVIDER_NAME
    assert follow_up["next_advice"] == "Continue current medicines."
    assert follow_up["next_action_date"] == "2026-08-27"
    assert follow_up["contacted_person"] == "Patient"
    assert follow_up["notify_patient"] is True


